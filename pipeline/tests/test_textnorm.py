from szdict.textnorm import cardinal, read_digits


def test_cardinals():
    assert [cardinal(n) for n in (0, 7, 10, 12, 20, 21, 100, 105, 110, 111, 1000, 1001, 1010, 2000, 2015, 10000, 10500, 20000, 100000, 1000000, 100000000, 120000000)] == [
        "零", "七", "十", "十二", "二十", "二十一", "一百", "一百零五", "一百一十", "一百一十一", "一千", "一千零一", "一千零一十", "两千",
        "两千零一十五", "一万", "一万零五百", "两万", "十万", "一百万", "一亿", "一亿二千万"]


def test_read_digits():
    cases = {
        "我9点去": "我九点去", "9:30见": "九点半见", "8:00开会": "八点开会", "7:05出发": "七点零五分出发", "10：45": "十点四十五分",
        "3个人": "三个人", "2个": "两个", "第2个": "第二个", "2月2号": "二月二号", "12点": "十二点", "2点半": "两点半",
        "2015年": "二零一五年", "打110": "打一百一十", "电话13800138000": "电话一三八零零一三八零零零", "007": "零零七",
        "3.5公里": "三点五公里", "50%": "百分之五十", "２０个": "二十个", "没有数字": "没有数字", "20000人": "两万人",
    }
    for src, want in cases.items():
        assert read_digits(src) == want, src
