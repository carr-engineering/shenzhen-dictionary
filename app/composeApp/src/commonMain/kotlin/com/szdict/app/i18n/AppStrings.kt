package com.szdict.app.i18n

import androidx.compose.runtime.Composable
import androidx.compose.runtime.staticCompositionLocalOf
import com.szdict.core.api.UiLang

/**
 * App-owned interface text (GLB-100): English source strings are the keys; zh-Hans and zh-Hant
 * tables translate them. Dictionary content keeps its source language.
 */
class AppStrings(val lang: UiLang) {
    fun text(english: String, vararg arguments: Any?): String {
        val template = when (lang) {
            UiLang.EN -> english
            UiLang.ZH_HANS -> SimplifiedChineseStrings[english] ?: english
            UiLang.ZH_HANT -> TraditionalChineseStrings[english] ?: SimplifiedChineseStrings[english] ?: english
        }
        if (arguments.isEmpty()) return template
        // Replace once: arguments may themselves contain braces or dollar signs.
        return Placeholder.replace(template) { match ->
            arguments.getOrNull(match.groupValues[1].toInt())?.toString() ?: match.value
        }
    }

    companion object {
        private val Placeholder = Regex("\\{(\\d+)\\}")
    }
}

val LocalStrings = staticCompositionLocalOf { AppStrings(UiLang.EN) }

@Composable
fun appStrings(): AppStrings = LocalStrings.current

